// Runs the test suite and writes PARITY.md: for each feature test file, how many
// comparisons against JHora 8.0's own output (golden/*) pass, plus which test
// files are self-consistency checks only.
// Usage: node tools/parity-report.mjs
import { execFileSync } from 'node:child_process';
import { readFileSync, writeFileSync, mkdtempSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join, basename } from 'node:path';

const out = join(mkdtempSync(join(tmpdir(), 'parity-')), 'vitest.json');
try {
  execFileSync(process.execPath, ['node_modules/vitest/vitest.mjs', 'run', '--reporter=json', `--outputFile=${out}`], { stdio: 'ignore' });
} catch { /* failing tests still write the report */ }
const report = JSON.parse(readFileSync(out, 'utf8'));

/** Test files whose assertions compare with JHora's captured output (golden/), and what they cover. */
const GOLDEN = {
  'positions.test.ts': 'planet and lagna longitudes (Swiss Ephemeris model as JHora uses it)',
  'longitudes.test.ts': 'Longitudes & Basic Info: special lagnas, upagrahas, arudhas, sphutas (56 bodies)',
  'vargas.test.ts': 'divisional chart signs (all default vargas)',
  'basics.test.ts': 'Key Info tables (taras, karakas, combustion, drekkanas, sahamas, ...), houses, KP, amsa rulers',
  'keyInfo.test.ts': 'Key Info text pane (panchanga, horas, kaala, sunrise/sunset, janma ghatis)',
  'strengths.test.ts': 'shadbala and its components, bhava bala, ishta/kashta, rashmis, vimsopaka',
  'otherStrengths.test.ts': 'amsa balas, avasthas, Tajaka balas',
  'ashtakavarga.test.ts': 'BAV/SAV/PAV, sodhana, sodhya pindas',
  'yogas.test.ts': 'yogas, all ten categories',
  'dasas.test.ts': 'nakshatra dasas, Narayana, Moola (dasa view texts)',
  'calcsDasas.test.ts': 'Vimsottari, Ashtottari, Kalachakra, Narayana, Sudasa with antardasas (complete calculations text)',
  'dasaGolden.test.ts': 'every rasi and other dasa, maha dasas and two antardasa lists',
  'tajakaGolden.test.ts': 'Tajaka charts: longitudes, Mudda and Patyayini dasas, Tajaka balas',
};
const rows = report.testResults.map((f) => {
  const name = basename(f.name);
  const src = readFileSync(f.name, 'utf8');
  const golden = name in GOLDEN;
  const tests = f.assertionResults;
  const pass = tests.filter((t) => t.status === 'passed').length;
  const fail = tests.filter((t) => t.status === 'failed').length;
  // first comment line of the file as its description
  const desc = GOLDEN[name] ?? (src.match(/^\/\/ (.+)$/m)?.[1] ?? '').slice(0, 110);
  return { name, golden, pass, fail, total: tests.length, desc };
}).sort((a, b) => Number(b.golden) - Number(a.golden) || a.name.localeCompare(b.name));

const sum = (xs, k) => xs.reduce((a, x) => a + x[k], 0);
const g = rows.filter((r) => r.golden), s = rows.filter((r) => !r.golden);
const line = (r) => `| ${r.name} | ${r.pass} | ${r.fail} | ${r.total ? ((100 * r.pass) / r.total).toFixed(1) : '-'}% | ${r.desc.replace(/\|/g, '/')} |`;
const md = [
  '# Parity with Jagannatha Hora 8.0',
  '',
  `Generated by \`node tools/parity-report.mjs\` on ${new Date().toISOString().slice(0, 10)}.`,
  '',
  `Comparisons against JHora's own output: **${sum(g, 'pass')} / ${sum(g, 'total')}** pass;`,
  `self-consistency and unit checks: ${sum(s, 'pass')} / ${sum(s, 'total')}.`,
  '',
  'Golden data: `golden/jhora` and `golden/jhora-v3` (18 charts, all tabs captured by `tools/harness`),',
  '`golden/jhora-dasas` (every rasi/other dasa), `golden/jhora-tajaka*` (Tajaka charts), `golden/calcs` (complete calculations).',
  'Tolerances are documented in each test (e.g. Kaala dasa within 2 h because of a millisecond sunrise residual).',
  '',
  '## Compared with JHora output',
  '',
  '| Test file | Pass | Fail | Rate | Covers |',
  '|---|---:|---:|---:|---|',
  ...g.map(line),
  '',
  '## Self-consistency and unit tests (no JHora output compared)',
  '',
  '| Test file | Pass | Fail | Rate | Covers |',
  '|---|---:|---:|---:|---|',
  ...s.map(line),
  '',
].join('\n');
writeFileSync('PARITY.md', md);
console.log(`PARITY.md: golden ${sum(g, 'pass')}/${sum(g, 'total')}, other ${sum(s, 'pass')}/${sum(s, 'total')}`);
