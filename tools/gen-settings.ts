// Generates src/settings/generated.ts from golden/jhora-defaults.ini, the file
// JHora 8.0 writes on first exit (its complete default settings).
//
//   node tools/gen-settings.ts
//
// Every key keeps JHora's name and section so jhora.ini files round-trip exactly.
// Indexed keys ("YearLength=3 365.242190", one line per slot) become arrays.
import { readFileSync, writeFileSync } from 'node:fs';

interface Spec { section: string; key: string; kind: 'int' | 'float' | 'str' | 'int[]' | 'float[]' | 'str[]'; default: unknown; length?: number }

const src = readFileSync('golden/jhora-defaults.ini', 'latin1').split(/\r?\n/);
const specs: Spec[] = [];
const byKey = new Map<string, Spec>();
let section = '';
for (const line of src) {
  if (!line.trim()) continue;
  const sec = /^\[(.+)\]$/.exec(line);
  if (sec) { section = sec[1]; continue; }
  const eq = line.indexOf('=');
  const key = line.slice(0, eq);
  const value = line.slice(eq + 1);
  const indexed = /^(\d+) (.*)$/.exec(value);
  const existing = byKey.get(key);
  if (existing && indexed) {
    (existing.default as unknown[]).push(scalar(indexed[2]));
    existing.length = (existing.default as unknown[]).length;
    continue;
  }
  if (indexed && !existing) {
    // Only an indexed key if the next line continues the series; decided below.
    const spec: Spec = { section, key, kind: 'int[]', default: [scalar(indexed[2])], length: 1 };
    byKey.set(key, spec); specs.push(spec);
    continue;
  }
  const spec: Spec = { section, key, kind: kindOf(value), default: scalar(value) };
  byKey.set(key, spec); specs.push(spec);
}
// Single-entry "indexed" keys are really scalars whose text happened to look like "n x".
for (const s of specs) {
  if (s.kind === 'int[]') {
    if (s.length === 1) { const v = `${0} ${(s.default as unknown[])[0]}`; s.kind = 'str'; s.default = v; delete s.length; continue; }
    const vals = s.default as unknown[];
    s.kind = vals.every((v) => typeof v === 'number' && Number.isInteger(v)) ? 'int[]'
      : vals.every((v) => typeof v === 'number') ? 'float[]' : 'str[]';
  }
}

function kindOf(v: string): Spec['kind'] {
  if (/^-?\d+$/.test(v)) return 'int';
  if (/^-?\d+\.\d+$/.test(v)) return 'float';
  return 'str';
}
function scalar(v: string): number | string {
  return /^-?\d+(\.\d+)?$/.test(v) ? Number(v) : v;
}
const tsType = (k: Spec['kind']) => ({ int: 'number', float: 'number', str: 'string', 'int[]': 'number[]', 'float[]': 'number[]', 'str[]': 'string[]' })[k];

let out = `// GENERATED by tools/gen-settings.ts from golden/jhora-defaults.ini — do not edit.\n`;
out += `// JHora 8.0's complete settings: ${specs.length} keys in ${new Set(specs.map((s) => s.section)).size} sections.\n\n`;
out += `export type IniKind = 'int' | 'float' | 'str' | 'int[]' | 'float[]' | 'str[]';\n`;
out += `export interface IniKeySpec { section: string; key: string; kind: IniKind; length?: number }\n\n`;
out += `export interface JhoraIni {\n`;
// A few keys contain dots (CustDivSettings.nCustDivN); quote those.
const prop = (k: string) => (/^[A-Za-z_$][\w$]*$/.test(k) ? k : JSON.stringify(k));
for (const s of specs) out += `  ${prop(s.key)}: ${tsType(s.kind)};\n`;
out += `}\n\nexport const INI_SPEC: readonly IniKeySpec[] = [\n`;
for (const s of specs) out += `  { section: ${JSON.stringify(s.section)}, key: ${JSON.stringify(s.key)}, kind: '${s.kind}'${s.length ? `, length: ${s.length}` : ''} },\n`;
out += `];\n\nexport const DEFAULTS: JhoraIni = {\n`;
for (const s of specs) out += `  ${prop(s.key)}: ${JSON.stringify(s.default)},\n`;
out += `};\n`;
writeFileSync('src/settings/generated.ts', out);
console.log(`wrote src/settings/generated.ts: ${specs.length} keys, ${specs.filter((s) => s.length).length} arrays`);
